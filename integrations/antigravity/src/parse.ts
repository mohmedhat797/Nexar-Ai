import { measured, unavailable } from '@nexar/contracts';
import type { ExecutionEvent, Measured, NexarErrorCode, UsageReport } from '@nexar/contracts';

/** Raw counters from `result.usage`; absent fields are undefined. */
export interface AgyUsageCounters {
  readonly inputTokens?: number;
  readonly outputTokens?: number;
  readonly thinkingTokens?: number;
  readonly cacheReadTokens?: number;
}

export interface ParsedAgyRun {
  /** The final `result` event was seen. */
  readonly sawResult: boolean;
  /** `result.status`, e.g. `SUCCESS`. */
  readonly status?: string;
  /** `result.response` (the final answer text). */
  readonly response?: string;
  /** `result.error`, flattened to a string. */
  readonly error?: string;
  readonly usage?: AgyUsageCounters;
  /** `result.num_turns`. */
  readonly turns?: number;
}

type Json = Readonly<Record<string, unknown>>;

function isRecord(v: unknown): v is Json {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

function num(v: unknown): number | undefined {
  return typeof v === 'number' && Number.isFinite(v) && v >= 0 ? v : undefined;
}

function str(v: unknown): string | undefined {
  return typeof v === 'string' ? v : undefined;
}

function counters(v: unknown): AgyUsageCounters | undefined {
  if (!isRecord(v)) return undefined;
  const out: { -readonly [K in keyof AgyUsageCounters]: AgyUsageCounters[K] } = {};
  const input = num(v['input_tokens']);
  if (input !== undefined) out.inputTokens = input;
  const output = num(v['output_tokens']);
  if (output !== undefined) out.outputTokens = output;
  const thinking = num(v['thinking_tokens']);
  if (thinking !== undefined) out.thinkingTokens = thinking;
  const cacheRead = num(v['cache_read_tokens']);
  if (cacheRead !== undefined) out.cacheReadTokens = cacheRead;
  return out;
}

function errorText(v: unknown): string | undefined {
  if (typeof v === 'string') return v;
  if (isRecord(v)) return str(v['message']) ?? str(v['code']);
  return undefined;
}

/** Incrementally folds `agy --output-format stream-json` stdout lines into a result. Pure: no I/O. */
export class AgyStreamParser {
  private run: ParsedAgyRun = { sawResult: false };
  private readonly announcedTools = new Set<number>();

  /** Consumes one stdout line; non-JSON and unrecognized lines are ignored. Returns progress events. */
  push(line: string): ExecutionEvent[] {
    const trimmed = line.trim();
    if (!trimmed.startsWith('{')) return [];
    let event: unknown;
    try {
      event = JSON.parse(trimmed);
    } catch {
      return [];
    }
    if (!isRecord(event)) return [];

    switch (event['type']) {
      case 'step_update':
        return this.step(event);
      case 'result':
        this.fold(event);
        return [];
      default:
        return [];
    }
  }

  result(): ParsedAgyRun {
    return this.run;
  }

  /** Tool names only (once per step): never `tool_info.parameters` or `.output`, they carry content. */
  private step(event: Json): ExecutionEvent[] {
    const info = event['tool_info'];
    if (!isRecord(info)) return [];
    const name = str(info['name']);
    if (name === undefined || name === '') return [];
    const index = num(event['step_index']);
    if (index !== undefined) {
      if (this.announcedTools.has(index)) return [];
      this.announcedTools.add(index);
    }
    return [{ type: 'tool-call', name }];
  }

  private fold(event: Json): void {
    const status = str(event['status']);
    const response = str(event['response']);
    const error = errorText(event['error']);
    const usage = counters(event['usage']);
    const turns = num(event['num_turns']);
    this.run = {
      sawResult: true,
      ...(status !== undefined ? { status } : {}),
      ...(response !== undefined ? { response } : {}),
      ...(error !== undefined ? { error } : {}),
      ...(usage !== undefined ? { usage } : {}),
      ...(turns !== undefined ? { turns } : {}),
    };
  }
}

/** Parses a whole stdout capture; convenience over {@link AgyStreamParser}. */
export function parseAgyStream(lines: Iterable<string>): ParsedAgyRun {
  const parser = new AgyStreamParser();
  for (const line of lines) parser.push(line);
  return parser.result();
}

const NOT_REPORTED = 'not reported by agy';
const SUBSCRIPTION = 'subscription; not reported by agy';

function reported(n: number | undefined): Measured<number> {
  return n === undefined ? unavailable(NOT_REPORTED) : measured(n);
}

/**
 * Maps `result.usage` to a {@link UsageReport}. No usage, or every counter 0/missing, is
 * `unavailable` (never a measured 0). `thinking_tokens` are added to output tokens: they are
 * generated by the model and billed as output. Cost is never known (subscription quota).
 */
export function toUsage(run: ParsedAgyRun): UsageReport {
  const u = run.usage;
  const total =
    (u?.inputTokens ?? 0) +
    (u?.outputTokens ?? 0) +
    (u?.thinkingTokens ?? 0) +
    (u?.cacheReadTokens ?? 0);
  const turns =
    run.turns !== undefined && run.turns > 0
      ? measured(run.turns)
      : unavailable<number>(NOT_REPORTED);
  if (u === undefined || total === 0) {
    return {
      inputTokens: unavailable(NOT_REPORTED),
      outputTokens: unavailable(NOT_REPORTED),
      costUsd: unavailable(SUBSCRIPTION),
      turns,
    };
  }
  const output =
    u.outputTokens === undefined && u.thinkingTokens === undefined
      ? undefined
      : (u.outputTokens ?? 0) + (u.thinkingTokens ?? 0);
  return {
    inputTokens: reported(u.inputTokens),
    outputTokens: reported(output),
    cacheReadTokens: reported(u.cacheReadTokens),
    costUsd: unavailable(SUBSCRIPTION),
    turns,
  };
}

/** The stderr line `agy` prints when a headless run ends on a model/agent error (exit 3). */
export interface AgyErrorLine {
  readonly status?: string;
  readonly code?: string;
  readonly retryable?: boolean;
}

/** Finds the last `AGY_ERROR: {json}` line; a malformed payload still yields `{}`. */
export function parseAgyErrorLine(stderr: string): AgyErrorLine | undefined {
  let found: AgyErrorLine | undefined;
  for (const raw of stderr.split('\n')) {
    const line = raw.trim();
    if (!line.startsWith('AGY_ERROR:')) continue;
    found = {};
    try {
      const body: unknown = JSON.parse(line.slice('AGY_ERROR:'.length));
      if (!isRecord(body)) continue;
      const status = str(body['status']);
      const code = errorText(body['code']);
      found = {
        ...(status !== undefined ? { status } : {}),
        ...(code !== undefined ? { code } : {}),
        ...(typeof body['retryable'] === 'boolean' ? { retryable: body['retryable'] } : {}),
      };
    } catch {
      // keep the empty marker
    }
  }
  return found;
}

const AUTH_FAILURE = /sign[ -]?in|oauth|unauthenticated|\b401\b/i;
const QUOTA_FAILURE = /quota|\b429\b|rate[ -]?limit|RESOURCE_EXHAUSTED/i;

/** Classifies a failure message into a Nexar error code. Auth is checked first. */
export function classifyFailure(message: string): NexarErrorCode {
  if (AUTH_FAILURE.test(message)) return 'AUTH_REQUIRED';
  if (QUOTA_FAILURE.test(message)) return 'QUOTA_EXHAUSTED';
  return 'PROVIDER_ERROR';
}

/** `agy` fell back to its own interactive sign-in (it would block forever with no browser). */
export function isInteractiveOAuth(line: string): boolean {
  return /interactive\s+oauth/i.test(line);
}

/** A stderr notice that a tool call was soft-denied (headless runs continue with exit 0). */
export function isPermissionDenial(line: string): boolean {
  return /permission.*denied|denied.*permission|soft[- ]?denied|auto[- ]?denied/i.test(line);
}
